#!/usr/bin/env python3
"""Reproducibly generate the graph-coloring DIMACS corpus fixtures."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def odd_wheel(cycle_vertices, colors, destination, satlib_trailer=False):
    """Encode an odd cycle plus a universal hub using one-hot colors."""
    vertices = cycle_vertices + 1
    hub = cycle_vertices
    edges = [(i, (i + 1) % cycle_vertices) for i in range(cycle_vertices)]
    edges += [(hub, i) for i in range(cycle_vertices)]
    clauses = []

    def variable(vertex, color):
        return vertex * colors + color + 1

    for vertex in range(vertices):
        clauses.append([variable(vertex, color) for color in range(colors)])
        for first in range(colors):
            for second in range(first + 1, colors):
                clauses.append([-variable(vertex, first), -variable(vertex, second)])
    for left, right in edges:
        for color in range(colors):
            clauses.append([-variable(left, color), -variable(right, color)])

    lines = [
        f"c odd wheel W_{cycle_vertices + 1}: C_{cycle_vertices} plus a universal hub",
        f"c generated by: python3 tests/generate_graph_coloring_corpus.py",
        f"c {colors}-coloring is UNSAT: the odd rim needs 3 colors, leaving none for the hub",
        f"p cnf {vertices * colors} {len(clauses)}",
    ]
    lines += [" ".join(map(str, clause)) + " 0" for clause in clauses]
    if satlib_trailer:
        lines += ["%", "0"]
    (ROOT / destination).write_text("\n".join(lines) + "\n", encoding="ascii")


odd_wheel(5, 3, "tests/corpus/odd_wheel_6_3color_unsat.cnf")
odd_wheel(7, 3, "tests/corpus/vendor/satlib_style_odd_wheel_8_3color.cnf", True)
